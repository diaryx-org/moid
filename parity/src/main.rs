//! Generates the golden vectors that `moid-ts` is held to.
//!
//! ```console
//! $ cargo run -p moid-parity -- moid-ts/test/vectors.json
//! ```
//!
//! The output is checked in, so the TypeScript suite runs with no Rust
//! toolchain present, and CI regenerates it and fails on any diff — a change to
//! the Rust that the port has not matched cannot land quietly.
//!
//! This program **records** what `moid` does; it never asserts what `moid`
//! ought to do. Ground truth lives in the library and its own tests. If a
//! vector looks wrong, the answer is a fix in `moid`, not here.

mod json;

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::process;

use json::{Doc, V};
use moid::{Alphabet, Minter, MoidError, SeededRng};

/// Bumped when the vector file's shape changes, so a stale checkout fails
/// loudly on the schema assertion instead of subtly on a missing field.
const SCHEMA: usize = 1;

/// Seeds for the raw PRNG vectors.
///
/// Weighted towards the values that break a 64-bit PRNG ported onto JavaScript
/// numbers: the `xorshift64` fixed point, the boundary where doubles stop
/// counting integers exactly (2^53), and the top of the `u64` range.
const RNG_SEEDS: &[u64] = &[
    0,
    1,
    7,
    42,
    0x9E37_79B9_7F4A_7C15,
    1 << 32,
    (1 << 53) - 1,
    1 << 53,
    (1 << 53) + 1,
    u64::MAX,
];

/// Seeds each minter configuration is exercised with.
const MINT_SEEDS: &[u64] = &[0, 1, 42, u64::MAX];

/// How many ids to draw from each (config, seed) pair. Enough that a divergence
/// in rejection sampling shows up: a rejected byte shifts the whole stream, so
/// the ids after the first rejection all move.
const IDS_PER_SEED: usize = 12;

/// A character no ASCII alphabet can contain, used to corrupt ids.
///
/// Astral on purpose: it is one `char` in Rust and two UTF-16 code units in
/// JavaScript, so any length or indexing logic that counts code units instead
/// of code points disagrees about it.
const ASTRAL: char = '\u{1F600}';

fn main() {
    let document = build();
    match env::args().nth(1) {
        Some(path) => {
            if let Err(e) = fs::write(&path, &document) {
                eprintln!("moid-parity: could not write {path}: {e}");
                process::exit(1);
            }
        }
        None => print!("{document}"),
    }
}

fn build() -> String {
    let specs = alphabet_specs();
    let mut doc = Doc::new();

    doc.field("schema", V::n(SCHEMA));
    doc.field(
        "note",
        V::s("Generated by `cargo run -p moid-parity`. Do not edit by hand."),
    );
    doc.section("alphabets", alphabets(&specs));
    doc.section("error_messages", error_messages());
    doc.section("alphabet_errors", alphabet_errors());
    doc.section("check_char", check_chars(&specs));
    doc.section("verify_check", verify_checks(&specs));
    doc.section("rng", rng_streams());
    doc.section("prefix_errors", prefix_errors(&specs));
    doc.section("mint", mints(&specs));
    doc.section("validate", validations(&specs));

    doc.finish()
}

// ---------------------------------------------------------------- alphabets

/// The alphabets every vector is drawn over: the three presets, plus customs
/// picked for their radix arithmetic.
fn alphabet_specs() -> Vec<(&'static str, Vec<u8>)> {
    vec![
        ("betanumeric", moid::presets::BETANUMERIC.to_vec()),
        ("noid_xdigit", moid::presets::NOID_XDIGIT.to_vec()),
        ("crockford32", moid::presets::CROCKFORD32.to_vec()),
        // Radix 2 divides 256: rejection sampling never rejects.
        ("binary", b"01".to_vec()),
        // Radix 3 leaves a remainder of 1, so exactly one byte value (255) is
        // rejected — the narrowest rejection window there is.
        ("ternary", b"abc".to_vec()),
        // Radix 95 rejects 66 of 256 byte values, so a stream diverges quickly
        // if rejection is wrong. Also carries `"` and `\`, which the JSON
        // writer has to escape, and a space, which is easy to trim by accident.
        ("printable_ascii", (0x20u8..=0x7e).collect()),
    ]
}

fn alphabet_of(specs: &[(&'static str, Vec<u8>)], id: &str) -> Alphabet {
    let bytes = specs
        .iter()
        .find(|(name, _)| *name == id)
        .map(|(_, bytes)| bytes)
        .expect("configs only reference declared alphabets");
    Alphabet::new(bytes).expect("declared alphabets are valid")
}

fn alphabets(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    specs
        .iter()
        .map(|(id, bytes)| {
            let alphabet = Alphabet::new(bytes).expect("declared alphabets are valid");
            V::Obj(vec![
                ("id", V::s(*id)),
                ("bytes_hex", V::s(hex(bytes))),
                ("radix", V::n(alphabet.radix())),
                ("as_str", V::s(alphabet.as_str())),
            ])
        })
        .collect()
}

// ------------------------------------------------------------------- errors

/// The stable name for a `MoidError`, matching `MoidErrorCode` in TypeScript.
fn code(error: &MoidError) -> &'static str {
    match error {
        MoidError::EmptyAlphabet => "EmptyAlphabet",
        MoidError::AlphabetTooLarge => "AlphabetTooLarge",
        MoidError::NonAsciiAlphabet => "NonAsciiAlphabet",
        MoidError::DuplicateSymbol => "DuplicateSymbol",
        MoidError::BadLength => "BadLength",
        MoidError::BadChar => "BadChar",
        MoidError::BadCheck => "BadCheck",
        MoidError::BadPrefix => "BadPrefix",
        MoidError::PrefixOutOfAlphabet => "PrefixOutOfAlphabet",
        MoidError::Entropy => "Entropy",
        // `MoidError` is `#[non_exhaustive]`. A new variant reaching here emits
        // a code the TypeScript does not know, and its message assertion fails
        // — which is the intended signal to port the variant.
        _ => "Unknown",
    }
}

fn error_messages() -> Vec<V> {
    [
        MoidError::EmptyAlphabet,
        MoidError::AlphabetTooLarge,
        MoidError::NonAsciiAlphabet,
        MoidError::DuplicateSymbol,
        MoidError::BadLength,
        MoidError::BadChar,
        MoidError::BadCheck,
        MoidError::BadPrefix,
        MoidError::PrefixOutOfAlphabet,
        MoidError::Entropy,
    ]
    .iter()
    .map(|error| {
        V::Obj(vec![
            ("code", V::s(code(error))),
            ("message", V::s(error.to_string())),
        ])
    })
    .collect()
}

/// Alphabet construction, valid and invalid. The invalid cases are chosen so
/// several rules break at once, pinning the *order* the checks run in.
fn alphabet_errors() -> Vec<V> {
    let cases: Vec<Vec<u8>> = vec![
        vec![],
        // 256 symbols and all duplicates: the length check has to win.
        vec![0u8; 256],
        vec![b'a', 0x80],
        vec![b'a', b'b', b'a'],
        // Non-ASCII *and* duplicated: the per-symbol ASCII check has to win.
        vec![0x80, 0x80],
        // A duplicate at index 1 precedes a non-ASCII at index 2, so scanning
        // in order reports the duplicate.
        vec![b'a', b'a', 0x80],
        // NUL is ASCII, so a one-symbol alphabet of it is legal.
        vec![0x00],
        vec![b'a'],
        (0x20u8..=0x7e).collect(),
        // Every ASCII code point: the largest alphabet that can exist.
        (0u8..=127).collect(),
        // One past it — 129 distinct bytes, the last outside ASCII.
        (0u8..=128).collect(),
    ];

    cases
        .iter()
        .map(|bytes| {
            let mut fields = vec![("bytes_hex", V::s(hex(bytes)))];
            match Alphabet::new(bytes) {
                Ok(alphabet) => {
                    fields.push(("ok", V::Bool(true)));
                    fields.push(("radix", V::n(alphabet.radix())));
                }
                Err(error) => {
                    fields.push(("ok", V::Bool(false)));
                    fields.push(("code", V::s(code(&error))));
                }
            }
            V::Obj(fields)
        })
        .collect()
}

// -------------------------------------------------------------- check chars

/// Bodies the check character is computed over.
///
/// Deliberately not restricted to well-formed ids: `check_char` is defined for
/// any string, counting out-of-alphabet characters as zero while still
/// advancing the position, and that clause is where a port most easily drifts.
fn check_char_bodies() -> Vec<String> {
    let mut bodies: Vec<String> = [
        "",
        "b",
        "bc",
        "bcdfg",
        "bcdfgh",
        "dxbcdfgh",
        "dxbbbbbb",
        "dybbbbbb",
        "b-d",
        "0000",
        "zzzzzzzzzzzz",
        "ABCDEFG",
        "01010101",
        "abc",
        " ",
        "  b  ",
        "\"\\",
        // One `char` in Rust, one code point in JavaScript, two UTF-8 bytes.
        "é",
        "bécd",
        // Base letter plus combining acute: two characters, not one.
        "e\u{301}",
        // Astral: one `char`, two UTF-16 code units. Iterating code units would
        // put every following character one position out.
        "b\u{1F600}d",
        "\u{1F600}",
        "\u{1F600}\u{1F600}b",
        "\u{1F600}b\u{1F600}c",
    ]
    .iter()
    .map(|s| (*s).to_string())
    .collect();

    // Long enough that a running sum kept in a JavaScript number would have to
    // be reduced as it goes rather than at the end.
    bodies.push("b".repeat(200));
    bodies.push("zzzzzzzzzzzzzzzzzzzz".repeat(50));
    bodies.push("bcdfghjkmnpqrstvwxyz23456789".repeat(9));
    bodies
}

fn check_chars(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    let bodies = check_char_bodies();
    let mut out = Vec::new();
    for (id, _) in specs {
        let alphabet = alphabet_of(specs, id);
        for body in &bodies {
            out.push(V::Obj(vec![
                ("alphabet", V::s(*id)),
                ("body", V::s(body.clone())),
                ("check", V::s(alphabet.check_char(body).to_string())),
            ]));
        }
    }
    out
}

fn verify_checks(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    let bodies = check_char_bodies();
    let mut out = Vec::new();
    for (id, _) in specs {
        let alphabet = alphabet_of(specs, id);
        for body in &bodies {
            // Each body twice: raw (usually wrong), and with its own correct
            // check character appended (always right).
            let corrected = format!("{body}{}", alphabet.check_char(body));
            for input in [body.clone(), corrected] {
                out.push(V::Obj(vec![
                    ("alphabet", V::s(*id)),
                    ("input", V::s(input.clone())),
                    ("ok", V::Bool(alphabet.verify_check(&input))),
                ]));
            }
        }
    }
    out
}

// ---------------------------------------------------------------------- rng

fn rng_streams() -> Vec<V> {
    RNG_SEEDS
        .iter()
        .map(|&seed| {
            let mut rng = SeededRng::new(seed);
            let bytes = (0..64).map(|_| V::n(rng.next_byte() as usize)).collect();
            V::Obj(vec![
                // Decimal *string*: a u64 past 2^53 does not survive JSON.parse
                // as a number, and two of these seeds are past it.
                ("seed", V::s(seed.to_string())),
                ("bytes", V::Arr(bytes)),
            ])
        })
        .collect()
}

// ------------------------------------------------------------------ minters

struct Config {
    id: &'static str,
    alphabet: &'static str,
    random_len: usize,
    check: bool,
    prefix: Option<&'static str>,
}

fn configs() -> Vec<Config> {
    let c = |id, alphabet, random_len, check, prefix| Config {
        id,
        alphabet,
        random_len,
        check,
        prefix,
    };
    vec![
        c("betanumeric-6-check", "betanumeric", 6, true, None),
        c("betanumeric-6-check-dx", "betanumeric", 6, true, Some("dx")),
        c("betanumeric-6-nocheck", "betanumeric", 6, false, None),
        // No random body at all: the id is the check character over the prefix.
        c("betanumeric-0-check", "betanumeric", 0, true, None),
        c("betanumeric-0-check-dx", "betanumeric", 0, true, Some("dx")),
        c("betanumeric-1-nocheck", "betanumeric", 1, false, None),
        c("betanumeric-32-check", "betanumeric", 32, true, None),
        c("noid_xdigit-8-check-b", "noid_xdigit", 8, true, Some("b")),
        c("crockford32-10-check", "crockford32", 10, true, None),
        c("binary-16-check", "binary", 16, true, None),
        c("ternary-12-check", "ternary", 12, true, None),
        c(
            "printable_ascii-8-check-hi",
            "printable_ascii",
            8,
            true,
            Some("hi"),
        ),
    ]
}

fn minter_for(config: &Config, specs: &[(&'static str, Vec<u8>)]) -> Minter {
    let mut minter = Minter::new(alphabet_of(specs, config.alphabet), config.random_len);
    if !config.check {
        minter = minter.without_check();
    }
    if let Some(prefix) = config.prefix {
        minter = minter
            .with_prefix(prefix)
            .expect("config prefixes are valid");
    }
    minter
}

/// The config fields, repeated on every vector so the TypeScript side rebuilds
/// the minter from the file rather than from a table it has to keep in sync.
fn config_fields(config: &Config, minter: &Minter) -> Vec<(&'static str, V)> {
    vec![
        ("config", V::s(config.id)),
        ("alphabet", V::s(config.alphabet)),
        ("random_len", V::n(config.random_len)),
        ("check", V::Bool(config.check)),
        (
            "prefix",
            match config.prefix {
                Some(prefix) => V::s(prefix),
                None => V::Null,
            },
        ),
        ("expected_length", V::n(minter.len())),
    ]
}

fn prefix_errors(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    let cases: &[(&str, &str)] = &[
        ("betanumeric", "dx"),
        ("betanumeric", ""),
        ("betanumeric", "a1"),
        ("betanumeric", "a"),
        ("betanumeric", "1"),
        ("betanumeric", "dxa"),
        ("betanumeric", "\u{1F600}"),
        ("betanumeric", "é"),
        ("binary", "01"),
        ("binary", "2"),
        ("crockford32", "AB"),
        ("crockford32", "ab"),
        ("printable_ascii", "hi"),
        ("printable_ascii", " "),
        ("printable_ascii", "\u{1F600}"),
    ];

    cases
        .iter()
        .map(|(alphabet_id, prefix)| {
            let minter = Minter::new(alphabet_of(specs, alphabet_id), 6);
            let mut fields = vec![("alphabet", V::s(*alphabet_id)), ("prefix", V::s(*prefix))];
            match minter.with_prefix(*prefix) {
                Ok(minter) => {
                    fields.push(("ok", V::Bool(true)));
                    fields.push(("expected_length", V::n(minter.len())));
                }
                Err(error) => {
                    fields.push(("ok", V::Bool(false)));
                    fields.push(("code", V::s(code(&error))));
                }
            }
            V::Obj(fields)
        })
        .collect()
}

fn mints(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    let mut out = Vec::new();
    for config in configs() {
        let minter = minter_for(&config, specs);
        for &seed in MINT_SEEDS {
            let mut rng = SeededRng::new(seed);
            // One RNG across all the ids: the stream must line up across the
            // whole run, not just for a single draw.
            let ids = (0..IDS_PER_SEED)
                .map(|_| V::s(minter.mint_seeded(&mut rng)))
                .collect();
            let mut fields = config_fields(&config, &minter);
            fields.push(("seed", V::s(seed.to_string())));
            fields.push(("ids", V::Arr(ids)));
            out.push(V::Obj(fields));
        }
    }
    out
}

// --------------------------------------------------------------- validation

/// One corruption at every position of `id`, plus the degenerate inputs.
///
/// Exhaustive over positions, but one replacement per position rather than
/// every symbol in the alphabet — this file records outcomes for the port to
/// match, so the value is in covering each position, not in enumerating the
/// substitution space. Whether a given substitution is *caught* is a property of
/// the radix (over a composite one some are invisible), and that law is asserted
/// in `moid-ts/test/reference.test.ts`, not here.
fn corruptions(alphabet: &Alphabet, id: &str) -> Vec<String> {
    let chars: Vec<char> = id.chars().collect();
    let mut out = vec![
        id.to_string(),
        String::new(),
        chars[..chars.len().saturating_sub(1)].iter().collect(),
        format!("{id}{}", alphabet.symbol(0)),
        chars.iter().rev().collect(),
    ];

    for (i, &original) in chars.iter().enumerate() {
        // Swap in a different symbol from the alphabet: right shape, wrong
        // content — the case only the check character can catch.
        out.push(replace(&chars, i, other_symbol(alphabet, original)));
        // Swap in a character no ASCII alphabet holds, keeping the code-point
        // count identical. Counting UTF-16 units here would report the wrong
        // failure.
        out.push(replace(&chars, i, ASTRAL));
    }
    out
}

fn replace(chars: &[char], index: usize, replacement: char) -> String {
    chars
        .iter()
        .enumerate()
        .map(|(i, &c)| if i == index { replacement } else { c })
        .collect()
}

/// Any symbol of `alphabet` other than `c`.
fn other_symbol(alphabet: &Alphabet, c: char) -> char {
    let first = alphabet.symbol(0);
    if first == c {
        alphabet.symbol(1 % alphabet.radix())
    } else {
        first
    }
}

fn validations(specs: &[(&'static str, Vec<u8>)]) -> Vec<V> {
    let mut out = Vec::new();
    for config in configs() {
        let minter = minter_for(&config, specs);
        let alphabet = alphabet_of(specs, config.alphabet);
        let mut rng = SeededRng::new(42);
        let id = minter.mint_seeded(&mut rng);

        for input in corruptions(&alphabet, &id) {
            let result = match minter.validate(&input) {
                Ok(()) => "ok",
                Err(error) => code(&error),
            };
            let mut fields = config_fields(&config, &minter);
            fields.push(("input", V::s(input)));
            fields.push(("result", V::s(result)));
            out.push(V::Obj(fields));
        }
    }
    out
}

// ------------------------------------------------------------------- shared

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        let _ = write!(out, "{byte:02x}");
    }
    out
}
